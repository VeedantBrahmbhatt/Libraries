import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

const dataRoot = new URL('../../frontend/public/data/', import.meta.url);
const catalogBytes = await readFile(new URL('catalog.json', dataRoot));
const manifest = JSON.parse(await readFile(new URL('manifest.json', dataRoot), 'utf8'));
const sha256 = createHash('sha256').update(catalogBytes).digest('hex');
if (sha256 !== manifest.files['catalog.json'].sha256) {
  throw new Error('The browser catalog checksum does not match its manifest.');
}
const books = JSON.parse(catalogBytes.toString('utf8'));
const ids = books.map(book => book.id);
if (ids.length !== manifest.books || new Set(ids).size !== ids.length) {
  throw new Error('The browser catalog has missing or duplicate book IDs.');
}
const source = `// Generated by scripts/sync-catalog.mjs from the checked browser sample.\n` +
  `export const CATALOG_SHA256 = ${JSON.stringify(sha256)};\n` +
  `export const KNOWN_BOOK_IDS = new Set(${JSON.stringify(ids)});\n`;
await writeFile(new URL('../worker/known-books.js', import.meta.url), source);
console.log(`Synced ${ids.length} book IDs from catalog ${sha256.slice(0, 12)}.`);
